"""Shared emit machinery: markers, safe block replacement, rule rendering."""

import re
from collections.abc import Callable
from dataclasses import dataclass

from rulewright.rules.model import Rule

START = "<!-- rulewright:start -->"
END = "<!-- rulewright:end -->"
GENERATED = "<!-- Generated by rulewright from rulewright.yaml. Edit that file, not this block. -->"


class MarkerError(Exception):
    """The target file has broken markers; refusing to guess where to write."""


@dataclass(frozen=True)
class Target:
    name: str
    path: str  # relative to the repo root
    render: Callable[[list[Rule]], str]  # content between the markers


def rule_text(rule: Rule) -> str:
    """One line of plain text. Marker strings and newlines cannot survive into a target file."""
    text = " ".join(rule.text.split())
    return re.sub(r"<!--\s*rulewright:(start|end)\s*-->", "", text, flags=re.I).strip()


def scope_note(rule: Rule) -> str:
    if rule.scope == ["**"]:
        return ""
    return " (applies to: " + ", ".join(f"`{s}`" for s in rule.scope) + ")"


def bullets(rules: list[Rule]) -> str:
    return "\n".join(f"- {rule_text(r)}{scope_note(r)}" for r in rules)


def block(content: str) -> str:
    return f"{START}\n{content}\n{END}"


def apply_block(existing: str | None, content: str) -> str:
    """Put `content` between the markers of `existing`, leaving everything else untouched.

    No file yet: the block becomes the file. File without markers: block is appended. Broken
    markers (one missing, duplicated or reversed): MarkerError, and nothing is written.
    """
    new_block = block(content)
    if existing is None:
        return new_block + "\n"
    newline = "\r\n" if "\r\n" in existing else "\n"
    new_block = new_block.replace("\n", newline)
    starts, ends = existing.count(START), existing.count(END)
    if starts == 0 and ends == 0:
        body = existing
        if body.strip():  # keep what is there, then one blank line before the block
            if not body.endswith(newline):
                body += newline
            if not body.endswith(newline * 2):
                body += newline
        else:
            body = ""
        return body + new_block + newline
    if starts != 1 or ends != 1 or existing.index(START) > existing.index(END):
        raise MarkerError(
            f"expected exactly one {START} followed by one {END}, "
            f"found {starts} start and {ends} end markers"
        )
    head, _, rest = existing.partition(START)
    _, _, tail = rest.partition(END)
    return head + new_block + tail
