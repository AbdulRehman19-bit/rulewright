from rulesmith.rules.emit.base import Target, bullets
from rulesmith.rules.model import Rule

HEADER = "Rules learned from this repo (generated by rulesmith from rulesmith.yaml):"


def render(rules: list[Rule]) -> str:
    # .cursorrules is plain text: no markdown heading, no generated-by comment
    return f"{HEADER}\n{bullets(rules)}"


TARGET = Target(name="cursor", path=".cursorrules", render=render)
